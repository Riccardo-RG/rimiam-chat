// Rebuild platform assets from the single hand-traced SVG. Requires the Sharp
// installation already provided by Next.js; no network or external tools.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import sharp from "sharp";

const root = fileURLToPath(new URL("../", import.meta.url));
const read = (name) => readFile(path.join(root, name), "utf8");
async function save(name, content) {
  const target = path.join(root, name);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, content);
}
const mark = await read("public/brand/rimiam-mark.svg");
const background = "#F7F8F5";
const icon = mark.replace(
  "</defs>",
  `</defs><rect width="1254" height="1254" fill="${background}"/>`,
);
await save("src/app/icon.svg", icon);
await save(
  "src/app/apple-icon.png",
  await sharp(Buffer.from(icon)).resize(180, 180).flatten().png().toBuffer(),
);
const catalog = "mobile/ios/Miriam/Assets.xcassets";
await save(
  `${catalog}/AppIcon.appiconset/AppIcon.png`,
  await sharp(Buffer.from(icon)).resize(1024, 1024).flatten().png().toBuffer(),
);
await save(
  `${catalog}/RIMIAMMark.imageset/RIMIAMMark.png`,
  await sharp(Buffer.from(mark)).resize(384, 384).png().toBuffer(),
);
await save(
  `${catalog}/RIMIAMMark.imageset/Contents.json`,
  JSON.stringify(
    {
      images: [{ filename: "RIMIAMMark.png", idiom: "universal", scale: "3x" }],
      info: { author: "xcode", version: 1 },
    },
    null,
    2,
  ) + "\n",
);

// Only our deliberately small SVG vocabulary is supported. Fail on unsupported
// geometry rather than silently exporting a partial Android logo.
const attribute = (text, name) => {
  const value = text.match(new RegExp(`\\b${name}="([^"]+)"`))?.[1];
  if (value === undefined) throw new Error(`Missing SVG attribute: ${name}`);
  return value;
};
const gradients = new Map(
  [
    ...mark.matchAll(/<linearGradient\b([^>]+)>([\s\S]*?)<\/linearGradient>/g),
  ].map(([, attrs, stops]) => [
    attribute(attrs, "id"),
    `<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="${attribute(attrs, "x1")}" android:startY="${attribute(attrs, "y1")}" android:endX="${attribute(attrs, "x2")}" android:endY="${attribute(attrs, "y2")}">${[
      ...stops.matchAll(/<stop\b([^>]+)\/>/g),
    ]
      .map(
        ([, stop], index) =>
          `<item android:offset="${index === 0 ? "0" : attribute(stop, "offset")}" android:color="${attribute(stop, "stop-color")}"/>`,
      )
      .join("")}</gradient></aapt:attr>`,
  ]),
);
const paths = [...mark.matchAll(/<path\b([^>]+)\/>/g)];
if (paths.length !== 18 || /<(?:g|polygon|circle|rect|image)\b/.test(mark))
  throw new Error("SVG geometry changed: review the platform exporter.");
const androidPaths = paths
  .map(([, attrs]) => {
    const fill = attribute(attrs, "fill");
    const gradientId = fill.match(/^url\(#([^)]+)\)$/)?.[1];
    const gradient = gradientId && gradients.get(gradientId);
    if (gradientId && !gradient) throw new Error("Unknown SVG gradient");
    return gradient
      ? `<path android:pathData="${attribute(attrs, "d")}">${gradient}</path>`
      : `<path android:fillColor="${fill}" android:pathData="${attribute(attrs, "d")}"/>`;
  })
  .join("\n    ");
const vector = (size, viewport, content) =>
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-brand-assets.mjs. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt" android:width="${size}dp" android:height="${size}dp" android:viewportWidth="${viewport}" android:viewportHeight="${viewport}">\n    ${content}\n</vector>\n`;
const drawables = "mobile/android/app/src/main/res/drawable";
await save(`${drawables}/rimiam_mark.xml`, vector(48, 1254, androidPaths));
await save(
  `${drawables}/icon_foreground.xml`,
  vector(
    108,
    108,
    `<group android:scaleX="0.0475" android:scaleY="0.0475" android:translateX="23.2" android:translateY="25.14">${androidPaths}</group>`,
  ),
);
console.log(
  "Generated web, iOS and Android brand assets from rimiam-mark.svg.",
);
