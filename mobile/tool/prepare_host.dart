import 'dart:io';

import 'configure_push_host.dart';
import 'legacy_storage_host.dart';
import 'host_icons.dart';
import 'ios_simulator_sdk.dart';

/// Builds a separate simulator project with the native settings that protect
/// local drafts. The host is disposable. Dart sources stay in the repository.
Future<void> main(List<String> args) async {
  final source = File.fromUri(Platform.script).parent.parent;
  String? appId, output;
  for (final arg in args) {
    if (arg.startsWith('--app-id=') && appId == null) {
      appId = arg.substring('--app-id='.length);
      if (!RegExp(r'^[a-z][a-z0-9]*(\.[a-z][a-z0-9]*)+$').hasMatch(appId)) {
        throw ArgumentError('Identificativo app non valido.');
      }
    } else if (arg.startsWith('--output=') && output == null) {
      output = arg.substring('--output='.length);
      if (output.isEmpty)
        throw ArgumentError('Directory di destinazione vuota.');
    } else {
      throw ArgumentError(
        'Opzioni consentite: --output=<directory>, --app-id=<identificativo>',
      );
    }
  }
  final host = output == null
      ? Directory(
          '${(await Directory.systemTemp.createTemp('rimiam-flutter-')).path}/rimiam_probe',
        )
      : Directory(output).absolute;
  if (await FileSystemEntity.type(host.path, followLinks: false) !=
      FileSystemEntityType.notFound) {
    throw StateError('Scegli una directory nuova. La destinazione esiste già.');
  }
  final create = await Process.start('flutter', [
    'create',
    '--no-pub',
    '--platforms=android,ios',
    '--org=test.rimiam',
    '--project-name=rimiam_probe',
    host.path,
  ], mode: ProcessStartMode.inheritStdio);
  if (await create.exitCode != 0)
    throw StateError('Creazione del progetto Flutter non riuscita.');
  for (final name in ['pubspec.yaml', 'pubspec.lock']) {
    await File('${source.path}/$name').copy('${host.path}/$name');
  }
  for (final folder in ['lib', 'test', 'assets']) {
    final base = Directory('${source.path}/$folder');
    await for (final entry in base.list(recursive: true)) {
      if (entry is! File) continue;
      final relative = entry.path.substring(source.path.length + 1);
      final destination = File('${host.path}/$relative');
      await destination.parent.create(recursive: true);
      await entry.copy(destination.path);
    }
  }
  // This test belongs to the counter app generated by the stock template.
  final templateTest = File('${host.path}/test/widget_test.dart');
  if (await templateTest.exists()) await templateTest.delete();

  Future<void> change(
    String path,
    String from,
    String to,
    int occurrences,
  ) async {
    final file = File('${host.path}/$path');
    final text = await file.readAsString();
    if (from.allMatches(text).length != occurrences) {
      throw StateError('Il template Flutter è cambiato. Verifica $path.');
    }
    await file.writeAsString(text.replaceAll(from, to));
  }

  await change(
    'android/app/src/main/AndroidManifest.xml',
    '<application',
    '<uses-permission android:name="android.permission.INTERNET" />\n'
        '    <uses-permission android:name="android.permission.RECORD_AUDIO" />\n'
        '    <uses-permission android:name="android.permission.MODIFY_AUDIO_SETTINGS" />\n'
        '    <application android:allowBackup="false"',
    1,
  );
  await change('android/app/src/main/AndroidManifest.xml', '</activity>', '''<meta-data android:name="flutter_deeplinking_enabled" android:value="false" />
            <intent-filter>
                <action android:name="android.intent.action.VIEW"/>
                <category android:name="android.intent.category.DEFAULT"/>
                <category android:name="android.intent.category.BROWSABLE"/>
                <data android:scheme="com.rimiam.chat"/>
            </intent-filter>
        </activity>''', 1);
  await change(
    'ios/Runner/Info.plist',
    '<key>CFBundleIdentifier</key>',
    '''<key>FlutterDeepLinkingEnabled</key><false/>
    <key>CFBundleURLTypes</key><array><dict>
        <key>CFBundleURLSchemes</key><array><string>com.rimiam.chat</string></array>
    </dict></array>
    <key>CFBundleIdentifier</key>''',
    1,
  );
  await change(
    'ios/Runner/Info.plist',
    '<key>LSRequiresIPhoneOS</key>',
    '<key>NSAppTransportSecurity</key>\n\t<dict><key>NSAllowsLocalNetworking</key><true/></dict>\n\t<key>LSRequiresIPhoneOS</key>',
    1,
  );
  await change(
    'ios/Runner/Info.plist',
    '<key>LSRequiresIPhoneOS</key>',
    '<key>NSMicrophoneUsageDescription</key><string>Registra un messaggio vocale o parla in una chiamata dello spazio.</string>\n'
        '<key>NSCameraUsageDescription</key><string>Scatta una foto da allegare.</string>\n'
        '<key>NSPhotoLibraryUsageDescription</key><string>Scegli le foto da allegare.</string>\n'
        '<key>LSRequiresIPhoneOS</key>',
    1,
  );
  await change(
    'android/app/src/main/kotlin/test/rimiam/rimiam_probe/MainActivity.kt',
    'class MainActivity : FlutterActivity()',
    r'''class MainActivity : FlutterActivity() {
    override fun configureFlutterEngine(engine: io.flutter.embedding.engine.FlutterEngine) {
        super.configureFlutterEngine(engine)
        io.flutter.plugin.common.MethodChannel(engine.dartExecutor.binaryMessenger, "rimiam/attachment_staging")
            .setMethodCallHandler { call, result ->
                if (call.method == "protectedDirectory") {
                    result.success(java.io.File(applicationContext.noBackupFilesDir, "attachments-v1").absolutePath)
                } else if (call.method == "temporaryDirectory") result.success(applicationContext.cacheDir.absolutePath)
                else result.notImplemented()
            }
    }
}''',
    1,
  );
  await change(
    'ios/Runner/AppDelegate.swift',
    'GeneratedPluginRegistrant.register(with: engineBridge.pluginRegistry)',
    r'''GeneratedPluginRegistrant.register(with: engineBridge.pluginRegistry)
    let channel = FlutterMethodChannel(name: "rimiam/attachment_staging", binaryMessenger: engineBridge.applicationRegistrar.messenger())
    channel.setMethodCallHandler { call, reply in
      if call.method == "temporaryDirectory" { reply(FileManager.default.temporaryDirectory.path); return }
      guard call.method == "protectedDirectory" else { reply(FlutterMethodNotImplemented); return }
      do {
        let fm = FileManager.default
        var directory = try fm.url(for: .applicationSupportDirectory, in: .userDomainMask, appropriateFor: nil, create: true)
          .appendingPathComponent("attachments-v1", isDirectory: true)
        try fm.createDirectory(at: directory, withIntermediateDirectories: true, attributes: [.protectionKey: FileProtectionType.complete])
        var values = URLResourceValues()
        values.isExcludedFromBackup = true
        try directory.setResourceValues(values)
        reply(directory.path)
      } catch { reply(FlutterError(code: "staging_unavailable", message: nil, details: nil)) }
    }''',
    1,
  );
  const bundle = 'PRODUCT_BUNDLE_IDENTIFIER = test.rimiam.rimiamProbe;';
  await change(
    'ios/Runner.xcodeproj/project.pbxproj',
    bundle,
    'CODE_SIGN_ENTITLEMENTS = Runner/LocalTest.entitlements;\n\t\t\t\t$bundle',
    3,
  );
  await File('${host.path}/ios/Runner/LocalTest.entitlements').writeAsString(
    '<?xml version="1.0" encoding="UTF-8"?>\n'
    '<plist version="1.0"><dict><key>keychain-access-groups</key><array/></dict></plist>\n',
  );
  await configurePushHost(host);
  await configureLegacyStorageHost(host);
  await change(
    'android/app/src/main/AndroidManifest.xml',
    'android:label="rimiam_probe"',
    'android:label="RIMIAM"',
    1,
  );
  await change(
    'ios/Runner/Info.plist',
    '<string>Rimiam Probe</string>',
    '<string>RIMIAM</string>',
    1,
  );
  await change(
    'ios/Runner/Info.plist',
    '<string>rimiam_probe</string>',
    '<string>RIMIAM</string>',
    1,
  );
  await change(
    'android/app/build.gradle.kts',
    '    buildTypes {',
    r'''    val releaseKeys = listOf("RIMIAM_ANDROID_KEYSTORE", "RIMIAM_ANDROID_STORE_PASSWORD",
        "RIMIAM_ANDROID_KEY_ALIAS", "RIMIAM_ANDROID_KEY_PASSWORD").map { providers.environmentVariable(it).orNull }
    val hasSigningKey = releaseKeys.all { !it.isNullOrBlank() }
    require(hasSigningKey || releaseKeys.all { it.isNullOrBlank() }) { "Incomplete RIMIAM release signing configuration" }
    if (hasSigningKey) {
        signingConfigs.create("rimiamRelease") {
            storeFile = file(releaseKeys[0]!!)
            storePassword = releaseKeys[1]
            keyAlias = releaseKeys[2]
            keyPassword = releaseKeys[3]
        }
    }
    buildTypes {''',
    1,
  );
  await change(
    'android/app/build.gradle.kts',
    '''            // TODO: Add your own signing config for the release build.
            // Signing with the debug keys for now, so `flutter run --release` works.
            signingConfig = signingConfigs.getByName("debug")''',
    '            signingConfig = signingConfigs.findByName("rimiamRelease")',
    1,
  );
  if (appId != null) {
    await change(
      'android/app/build.gradle.kts',
      'test.rimiam.rimiam_probe',
      appId,
      2,
    );
    final activity = File(
      '${host.path}/android/app/src/main/kotlin/test/rimiam/rimiam_probe/MainActivity.kt',
    );
    await change(
      'android/app/src/main/kotlin/test/rimiam/rimiam_probe/MainActivity.kt',
      'package test.rimiam.rimiam_probe',
      'package $appId',
      1,
    );
    final newPath =
        '${host.path}/android/app/src/main/kotlin/${appId.replaceAll('.', '/')}/MainActivity.kt';
    await File(newPath).parent.create(recursive: true);
    await activity.rename(newPath);
    await change(
      'ios/Runner.xcodeproj/project.pbxproj',
      'PRODUCT_BUNDLE_IDENTIFIER = test.rimiam.rimiamProbe',
      'PRODUCT_BUNDLE_IDENTIFIER = $appId',
      6,
    );
  }
  await writeHostIcons(host, File('${source.path}/tool/app_icon.png'));
  await writeSimulatorSDKCompatibility(host);
  stdout.writeln('Progetto Flutter: ${host.path}');
}
