// Native reuses the Web interface copy. Keep user data outside these catalogs.
import { readFileSync, writeFileSync } from "node:fs";
import { betaRules } from "../../src/shared/beta-rules";

const source = new URL("../../src/shared/i18n/", import.meta.url);
const catalog: Record<string, string> = {};
for (const name of [
  "en.json",
  "tools.en.json",
  "account.en.json",
  "chat.en.json",
  "mobile.en.json",
]) {
  Object.assign(catalog, JSON.parse(readFileSync(new URL(name, source), "utf8")));
}

const check = process.argv.includes("--check");
function sync(path: string, content: string) {
  const file = new URL(path, import.meta.url);
  if (check) {
    if (readFileSync(file, "utf8") !== content)
      throw new Error("Rigenera i dati Flutter con mobile/tool/sync_ui_catalog.ts");
  } else writeFileSync(file, content);
}
const sorted = Object.fromEntries(
  Object.entries(catalog).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
);
sync("../assets/ui.en.json", JSON.stringify(sorted) + "\n");
// Bind the approved English reading to the exact revision and source wording.
sync(
  "../lib/beta_rule_identity.dart",
  "// Generated by tool/sync_ui_catalog.ts from src/shared/beta-rules.ts.\n" +
    "const publishedBetaVersion = " + JSON.stringify(betaRules.version) + ";\n" +
    "const publishedBetaText =\n    " + JSON.stringify(betaRules.text) + ";\n",
);
